JUNG_STROKES = [2, 3, 3, 4, 2, 3, 3, 4, 2, 4, 5, 3, 3, 2, 4, 5, 3, 3, 1, 2, 1]

# 종성 획수 (인덱스 0 = 받침 없음)
JONG_STROKES = [0, 2, 2, 4, 3, 5, 4, 4, 2, 4, 2, 3, 4, 3, 4, 4, 5, 4, 4, 2, 4, 3, 4, 4, 4, 3, 4, 6]


def decompose_hangul(char: str):
    """한글 문자를 초성/중성/종성 인덱스로 분해"""
    code = ord(char) - 0xAC00
    if code < 0 or code > 11171:
        return None, None, None
    jong = code % 28
    jung = (code // 28) % 21
    cho = code // 28 // 21
    return cho, jung, jong


def get_char_strokes(char: str) -> int:
    """한글 문자의 획수 반환 (원획법 기반)"""
    if '\uAC00' <= char <= '\uD7A3':  # 한글 완성형 범위
        cho, jung, jong = decompose_hangul(char)
        if cho is None:
            return 1
        cho_s = CHO_STROKES[cho] if cho < len(CHO_STROKES) else 1
        jung_s = JUNG_STROKES[jung] if jung < len(JUNG_STROKES) else 1
        jong_s = JONG_STROKES[jong] if jong < len(JONG_STROKES) else 0
        return cho_s + jung_s + jong_s
    # 한글 이외 문자(한자, 영문, 숫자 등)는 1획으로 처리
    return 1


def analyze_name(name: str) -> dict:
    """
    이름 획수 분석 및 81수리 해석

    Args:
        name: 성+이름 문자열 (공백 포함 가능)

    Returns:
        분석 결과 딕셔너리
    """
    name = name.replace(" ", "").strip()
    if not name:
        return None

    chars = list(name)
    strokes = [get_char_strokes(c) for c in chars]
    total = sum(strokes)

    def get_suri_info(n: int) -> dict:
        n = n % 81
        if n == 0:
            n = 81
        return SURI_81.get(n, {
            "name": f"{n}수",
            "type": "중길",
            "desc": "개성 있는 수리입니다. 노력으로 좋은 결과를 만들어낼 수 있습니다."
        })

    # 전체 81수리
    suri_num = total % 81
    if suri_num == 0:
        suri_num = 81
    suri = get_suri_info(suri_num)

    # 원형이정(元亨利貞) 4격 계산
    # 성 1글자, 이름 1~2글자 구조 가정
    if len(chars) >= 2:
        won_num = sum(strokes[1:]) % 81 or 81    # 원격: 이름자 획수 합
        hyung_num = (strokes[0] + strokes[1]) % 81 or 81  # 형격: 성 + 이름 첫자
        i_num = sum(strokes[1:]) % 81 or 81      # 이격: 이름자 획수 합
        jeong_num = total % 81 or 81             # 정격: 전체 획수 합
    else:
        won_num = hyung_num = i_num = jeong_num = total % 81 or 81

    # 오행 분석 (획수 끝자리 기준)
    element_map = {
        1: "木", 2: "木",
        3: "火", 4: "火",
        5: "土", 6: "土",
        7: "金", 8: "金",
        9: "水", 0: "水"
    }
