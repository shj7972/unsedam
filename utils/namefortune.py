# 초성 획수 (인덱스 순서: ㄱ ㄴ ㄷ ㄹ ㅁ ㅂ ㅅ ㅇ ㅈ ㅊ ㅋ ㅌ ㅍ ㅎ ㄲ ㄸ ㅃ ㅆ ㅉ)
CHO_STROKES = [2, 2, 3, 5, 4, 4, 2, 1, 3, 4, 3, 4, 4, 3, 4, 6, 8, 4, 6]

