def get_all_articles() -> list:
    """전체 아티클 목록 반환 (최신순)"""
    return sorted(ARTICLES, key=lambda x: x['date'], reverse=True)


def get_article_by_slug(slug: str):
    """slug로 특정 아티클 반환"""
    for article in ARTICLES:
        if article['slug'] == slug:
            return article
    return None


def get_articles_by_category(category: str) -> list:
    """카테고리별 아티클 목록 반환"""
    return [a for a in ARTICLES if a['category'] == category]


def get_related_articles(current_slug: str, limit: int = 3) -> list:
    """현재 아티클과 관련된 아티클 반환 (같은 카테고리 우선, 나머지는 최신순)"""
    current = get_article_by_slug(current_slug)
    if not current:
        return get_all_articles()[:limit]

    same_cat = [a for a in ARTICLES if a['category'] == current['category'] and a['slug'] != current_slug]
    others = [a for a in ARTICLES if a['category'] != current['category']]

    result = same_cat + others
    result = sorted(result, key=lambda x: x['date'], reverse=True)
    return result[:limit]


